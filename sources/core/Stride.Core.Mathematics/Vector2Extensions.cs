            for (int i = 0; i < source.Length; ++i)
            {
                destination[i] = Vector2.TransformCoordinate(source[i], transform);
            }
        }

        /// <summary>
        /// Performs a normal transformation on an array of vectors using the given <see cref="System.Numerics.Matrix4x4"/>.
        /// </summary>
        /// <param name="source">The array of normal vectors to transform.</param>
        /// <param name="transform">The transformation <see cref="System.Numerics.Matrix4x4"/>.</param>
        /// <param name="destination">The array for which the transformed vectors are stored.
        /// This array may be the same array as <paramref name="source"/>.</param>
        /// <exception cref="ArgumentNullException">Thrown when <paramref name="source"/> or <paramref name="destination"/> is <c>null</c>.</exception>
        /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="destination"/> is shorter in length than <paramref name="source"/>.</exception>
        /// <remarks>
        /// A normal transform performs the transformation with the assumption that the w component
        /// is zero. This causes the fourth row and fourth column of the matrix to be unused. The
        /// end result is a vector that is not translated, but all other transformation properties
        /// apply. This is often preferred for normal vectors as normals purely represent direction
        /// rather than location because normal vectors should not be translated.
        /// </remarks>
        public static void TransformNormal(Vector2[] source, in Matrix4x4 transform, Vector2[] destination)
        {
            if (source == null)
                throw new ArgumentNullException(nameof(source));
            if (destination == null)
                throw new ArgumentNullException(nameof(destination));
            if (destination.Length < source.Length)
                throw new ArgumentOutOfRangeException(nameof(destination), "The destination array must be of same length or larger length than the source array.");

            for (int i = 0; i < source.Length; ++i)
            {
                destination[i] = Vector2.TransformNormal(source[i], transform);
            }
        }

        /// <summary>
        /// Divides a numerator by a vector.
        /// </summary>
        /// <param name="numerator">The numerator.</param>
        /// <param name="value">The value.</param>
        /// <returns>The scaled vector.</returns>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static Vector2 operator /(float numerator, Vector2 value)
        {
            return new Vector2(numerator / value.X, numerator / value.Y);
        }

    }

    extension(Vector2 vector2)
    {
        /// <summary>
        /// Gets a value indicting whether this instance is normalized.
        /// </summary>
        public bool IsNormalized
        {
            get { return MathF.Abs((vector2.X * vector2.X) + (vector2.Y * vector2.Y) - 1f) < MathUtil.ZeroTolerance; }
        }

        /// <summary>
        /// Creates an array containing the elements of the vector.
        /// </summary>
        /// <returns>A two-element array containing the components of the vector.</returns>
        public float[] ToArray()
        {
            return [vector2.X, vector2.Y];
        }

        /// <summary>
        /// Determines whether the specified <see cref="System.Numerics.Vector2"/> is within <see cref="MathUtil.ZeroTolerance"/> for equality to this instance.
        /// </summary>
        /// <param name="other">The <see cref="System.Numerics.Vector2"/> to compare with this instance.</param>
        /// <returns>
        /// <c>true</c> if the specified <see cref="System.Numerics.Vector2"/> is equal or almost equal to this instance; otherwise, <c>false</c>.
        /// </returns>
        public bool NearEquals(Vector2 other)
        {
            return MathF.Abs(other.X - vector2.X) < MathUtil.ZeroTolerance &&
                MathF.Abs(other.Y - vector2.Y) < MathUtil.ZeroTolerance;
        }

        /// <summary>
        /// Deconstructs the vector's components into named variables.
        /// </summary>
        /// <param name="x">The X component</param>
        /// <param name="y">The Y component</param>
        public void Deconstruct(out float x, out float y)
        {
            x = vector2.X;
            y = vector2.Y;
        }

    }
