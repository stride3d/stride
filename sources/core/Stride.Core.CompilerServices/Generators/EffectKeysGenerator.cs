using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Stride.Core.CompilerServices.Common;

namespace Stride.Core.CompilerServices.Generators;

[Generator]
public sealed class EffectKeysGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var typeProvider = context.SyntaxProvider.ForAttributeWithMetadataName(WellKnownReferences.EffectKeysAttributeName, (node, _) =>
        {
            return node is ClassDeclarationSyntax or StructDeclarationSyntax or RecordDeclarationSyntax;
        },
        (context, _) =>
        {
            if (context.TargetSymbol is not INamedTypeSymbol type)
                return default;

            var keyNamePrefix = context.Attributes.FirstOrDefault()?.NamedArguments.FirstOrDefault(arg => arg.Key == "KeyNamePrefix").Value.Value as string;

            return EffectKeysType.FromSymbol(type, context.SemanticModel.Compilation, keyNamePrefix);
        }).Where(t => t != default);

        context.RegisterImplementationSourceOutput(typeProvider, Generate);
    }

    private static void Generate(SourceProductionContext context, EffectKeysType type)
    {
        const int OuterIndent = 8;
        const int InnerIndent = 12;

        var fields = new StringBuilder();
        var unsafeAccessors = new StringBuilder();
        foreach (var field in type.Fields)
        {
            var keyName = $"{type.KeyNamePrefix}.{field.Name}";

            fields.Append(' ', InnerIndent);
            fields.Append("global::Stride.Rendering.Generated.EffectKeysRegistration.Merge(");

            if (field.NeedsUnsafeAccessor)
            {
                unsafeAccessors
                    .Append(' ', OuterIndent)
                    .Append("[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticField, Name = ")
                    .Append(SymbolDisplay.FormatLiteral(field.Name, true))
                    .AppendLine(")]");
                if (field.UnsafeAccessorTypeName is not null)
                {
                    unsafeAccessors
                        .Append(' ', OuterIndent)
                        .Append("[return: global::System.Runtime.CompilerServices.UnsafeAccessorType(")
                        .Append(SymbolDisplay.FormatLiteral(field.UnsafeAccessorTypeName, true))
                        .AppendLine(")]");

                    unsafeAccessors
                        .Append(' ', OuterIndent)
                        .Append("private extern static ref object");
                }
                else
                {
                    unsafeAccessors
                        .Append(' ', OuterIndent)
                        .Append("private extern static ref ")
                        .Append(field.FieldType);
                }
                unsafeAccessors.Append(" Get_")
                    .Append(field.Name)
                    .Append('(');
                if (type.IsStatic || type.NeedsUnsafeAccessor)
                {
                    unsafeAccessors
                        .Append("[global::System.Runtime.CompilerServices.UnsafeAccessorType(")
                        .Append(SymbolDisplay.FormatLiteral(type.UnsafeAccessorTypeName!, true))
                        .Append(")] object");
                }
                else
                {
                    unsafeAccessors.Append(type.FullyQualifiedName);
                }
                unsafeAccessors.AppendLine(" unused);");

                if (field.UnsafeAccessorTypeName is not null)
                {
                    fields.Append("(global::Stride.Rendering.ParameterKey)(");
                }
                fields
                    .Append("global::Stride.Rendering.Generated.EffectKeysRegistration.Get_")
                    .Append(field.Name)
                    .Append("(default)");
                if (field.UnsafeAccessorTypeName is not null)
                {
                    fields.Append(')');
                }
            }
            else
            {
                fields
                    .Append(type.FullyQualifiedName)
                    .Append('.')
                    .Append(field.Name);
            }

            fields
                .Append(", ")
                .Append(SymbolDisplay.FormatLiteral(keyName, true))
                .AppendLine(");");
        }

        var typeOfString = type.NeedsUnsafeAccessor
            ? $"global::System.Type.GetType({SymbolDisplay.FormatLiteral(type.ReflectionName!, true)}, throwOnError: true)"
            : $"typeof({type.FullyQualifiedName})";

        context.AddSource(type.GetSafeHintName(), $$"""
            // <auto-generated/>
            namespace Stride.Rendering.Generated
            {
                file static class EffectKeysRegistration
                {
                    [global::System.Runtime.CompilerServices.ModuleInitializer]
                    internal static void Register()
                    {
            {{fields}}        }
                    private static void Merge(global::Stride.Rendering.ParameterKey key, string name)
                    {
                        if (key is not null)
                        {
                            global::Stride.Rendering.ParameterKeys.Merge(key, {{typeOfString}}, name);
                        }
                    }
            {{unsafeAccessors}}    }
            }
            """);
    }

    private readonly record struct EffectKeysType(string FullyQualifiedName, string? ReflectionName, string? UnsafeAccessorTypeName, string Name, string KeyNamePrefix, bool IsStatic, bool NeedsUnsafeAccessor, EquatableSet<EffectKeyField> Fields)
    {
        public string GetSafeHintName()
        {
            using var sha1 = SHA1.Create();
            byte[] hashBytes = sha1.ComputeHash(Encoding.UTF8.GetBytes(FullyQualifiedName));
            string hash = BitConverter.ToString(hashBytes).Replace("-", "")[..8];

            return $"{Name}_{hash}.g.cs";
        }

        public static EffectKeysType FromSymbol(INamedTypeSymbol type, Compilation compilation, string? keyNamePrefix)
        {
            if (type.HasGenericParameters())
                return default;

            var typeNeedsUnsafeAccessor = !compilation.IsSymbolAccessibleWithinThisAssembly(type);

            List<EffectKeyField> fields = [];
            foreach (var member in type.GetMembers())
            {
                if (member is not IFieldSymbol { IsStatic: true } staticField)
                    continue;

                if (!IsAssignableToParameterKey(staticField.Type))
                    continue;

                var fieldNeedsUnsafeAccessor = typeNeedsUnsafeAccessor || !compilation.IsSymbolAccessibleWithinThisAssembly(staticField);
                var fieldType = staticField.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var fieldUnsafeAccessorTypeName = compilation.IsSymbolAccessibleWithinThisAssembly(staticField.Type) ? null : staticField.Type.GetUnsafeAccessorTypeName();

                fields.Add(new(staticField.Name, fieldNeedsUnsafeAccessor, fieldType, fieldUnsafeAccessorTypeName));
            }

            if (fields.Count == 0)
                return default;

            var name = type.Name;
            if (string.IsNullOrEmpty(keyNamePrefix))
            {
                keyNamePrefix = name.EndsWith("Keys", StringComparison.Ordinal) && name.Length > 4 ? name[..^4] : name;
            }
            var fullyQualifiedName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var reflectionName = typeNeedsUnsafeAccessor ? type.GetReflectionName() : null;
            var unsafeAccessorTypeName = typeNeedsUnsafeAccessor || type.IsStatic ? type.GetUnsafeAccessorTypeName() : null;
            return new(fullyQualifiedName, reflectionName, unsafeAccessorTypeName, name, keyNamePrefix!, type.IsStatic, typeNeedsUnsafeAccessor, new(fields));
        }

        private static bool IsAssignableToParameterKey(ITypeSymbol type)
        {
            var current = type;
            while (current is not null)
            {
                if (IsParameterKey(current))
                    return true;

                current = current.BaseType?.OriginalDefinition;
            }
            return false;
        }

        private static bool IsParameterKey(ITypeSymbol type)
        {
            return type is INamedTypeSymbol
            {
                Name: "ParameterKey",
                Arity: 0,
                ContainingNamespace:
                {
                    Name: "Rendering",
                    ContainingNamespace:
                    {
                        Name: "Stride",
                        ContainingNamespace: null or { IsGlobalNamespace: true }
                    }
                },
            };
        }
    }

    /// <summary>
    /// The data for an effect key field
    /// </summary>
    /// <param name="Name">The name of the field</param>
    /// <param name="NeedsUnsafeAccessor">Indicates whether the field requires an unsafe accessor to access it</param>
    /// <param name="FieldType">The type of the field</param>
    /// <param name="UnsafeAccessorTypeName">The string for UnsafeAccessorType if the field type is inaccessible</param>
    private readonly record struct EffectKeyField(string Name, bool NeedsUnsafeAccessor, string FieldType, string? UnsafeAccessorTypeName);
}
