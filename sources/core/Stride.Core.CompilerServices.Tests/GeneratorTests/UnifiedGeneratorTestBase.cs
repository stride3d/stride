using System.Text;
using Microsoft.CodeAnalysis.CSharp.Testing;
using Microsoft.CodeAnalysis.Testing;
using Microsoft.CodeAnalysis.Text;
using Stride.Core.CompilerServices.Generators;
using Stride.Core.Reflection;

namespace Stride.Core.CompilerServices.Tests.GeneratorTests;

public abstract class UnifiedGeneratorTestBase
{
    protected CSharpSourceGeneratorTest<UnifiedGenerator, DefaultVerifier> Context { get; }

    public UnifiedGeneratorTestBase()
    {
        Context = new()
        {
            ReferenceAssemblies = ReferenceAssemblies.Net.Net100
        };
        Context.TestState.AdditionalReferences.Add(typeof(AssemblyScanAttribute).Assembly);
    }

    protected async Task TestGeneration(string testCode, string expectedGeneratedCode, string expectedFileName = UnifiedGenerator.FileName, CancellationToken cancellationToken = default)
    {
        Context.TestCode = testCode;
        Context.TestState.GeneratedSources.Add((typeof(UnifiedGenerator), expectedFileName, SourceText.From(expectedGeneratedCode.Replace("\r", null), Encoding.UTF8, SourceHashAlgorithm.Sha256)));
        await Context.RunAsync(cancellationToken);
    }

    protected static string ExpectedAssemblyScanCode(string scanType, string[] scannedTypes)
    {
        var dependencies = string.Join(Environment.NewLine, scannedTypes.Select(type =>
            $"        [global::System.Diagnostics.CodeAnalysis.DynamicDependencyAttribute(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicConstructors, typeof(global::{type}))]")) + Environment.NewLine;
        var typeList = string.Join(", ", scannedTypes.OrderBy(type => type, StringComparer.Ordinal).Select(type => $"typeof(global::{type})"));

        return $$"""
            // <auto-generated/>
            namespace Stride.Core.CompilerServices.AutoGenerated.ModuleInitializer
            {
                file static class ModuleInitializer
                {
                    [global::System.Runtime.CompilerServices.ModuleInitializer]
                    public static void Initialize()
                    {
                        global::Stride.Core.Serialization.AssemblyScan.AssemblyScanResults.Initialize();
                    }
                }
            }
            namespace Stride.Core.Serialization.AssemblyScan
            {
                file static partial class AssemblyScanResults
                {
            {{dependencies}}        public static void Initialize()
                    {
                        global::Stride.Core.Reflection.AssemblyRegistry.RegisterScanTypes(
                            typeof(global::Stride.Core.Serialization.AssemblyScan.AssemblyScanResults).Assembly,
                            static () => new global::Stride.Core.Reflection.AssemblyRegistry.ScanTypes(
                                new global::System.Collections.Generic.Dictionary<global::System.Type, global::System.Collections.Generic.List<global::System.Type>>
                                {
                                    {
                                        typeof(global::{{scanType}}),
                                        new global::System.Collections.Generic.List<global::System.Type> { {{typeList}}, }
                                    },

                                }
                            )
                        );
                    }
                }
            }
            """;
    }
}
