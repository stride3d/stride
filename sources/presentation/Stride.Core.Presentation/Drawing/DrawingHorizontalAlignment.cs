namespace Stride.Core.Presentation.Drawing;

/// <summary>
/// How a text of a drawing is placed horizontally around its point.
/// </summary>
public enum DrawingHorizontalAlignment
{
    /// <summary>
    /// The text starts at the point.
    /// </summary>
    Left,

    /// <summary>
    /// The text is centered on the point.
    /// </summary>
    Center,

    /// <summary>
    /// The text ends at the point.
    /// </summary>
    Right,
}
