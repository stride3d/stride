namespace Stride.Core.Presentation.Drawing;

/// <summary>
/// How a text of a drawing is placed vertically around its point.
/// </summary>
public enum DrawingVerticalAlignment
{
    /// <summary>
    /// The top of the text is at the point.
    /// </summary>
    Top,

    /// <summary>
    /// The text is centered on the point.
    /// </summary>
    Center,

    /// <summary>
    /// The bottom of the text is at the point.
    /// </summary>
    Bottom,
}
