using System;
using System.IO;
using System.Linq;
using System.Text;

using Stride.Graphics;

namespace Stride.Shaders.Compiler;

/// <summary>
///   Writes Effect bytecode as C# source code: a static byte array field, for an Effect embedded in an assembly.
/// </summary>
/// <remarks>
///   The output only depends on the bytecode and the parameters: the same bytecode always gives the same file.
/// </remarks>
public static class EffectBytecodeSourceWriter
{
    /// <summary>
    ///   The name of the file for an Effect, from <see cref="EffectSourceCodeKeys"/>: <c>Effect.field.Platform.Profile.cs</c>.
    /// </summary>
    public static string GetFileName(string name, CompilerParameters parameters)
    {
        var fieldName = parameters.Get(EffectSourceCodeKeys.FieldName);
        if (fieldName.StartsWith("binary", StringComparison.Ordinal))
        {
            fieldName = fieldName.Substring("binary".Length);
            if (char.IsUpper(fieldName[0]))
                fieldName = char.ToLower(fieldName[0]) + fieldName[1..];
        }
        return $"{name}.{fieldName}.{parameters.EffectParameters.Platform}.{parameters.EffectParameters.Profile}.cs";
    }

    /// <summary>
    ///   Writes C# source code for an Effect's bytecode as a static byte array field.
    /// </summary>
    /// <param name="name">
    ///   The name of the Effect. Used for labeling and as a default class name if none is specified in the compiler parameters.
    /// </param>
    /// <param name="parameters">The compiler parameters used to compile the Effect (<see cref="EffectSourceCodeKeys"/>).</param>
    /// <param name="bytecode">The Effect bytecode to embed.</param>
    /// <param name="writer">The text writer to which the source code is written.</param>
    /// <param name="generator">How the file is generated, written in its header.</param>
    public static void Write(string name, CompilerParameters parameters, EffectBytecode bytecode, TextWriter writer, string generator)
    {
        var buffer = new MemoryStream();
        bytecode.WriteTo(buffer);

        var bufferAsText = new StringBuilder();
        var bufferArray = buffer.ToArray();
        for (int i = 0; i < bufferArray.Length; i++)
        {
            bufferAsText.Append(bufferArray[i]).Append(", ");
            if (i > 0 && (i % 64) == 0)
                bufferAsText.Append('\n');
        }

        // The generated file only holds the bytecode field, one part of a class declared elsewhere
        var modifiers = parameters.Get(EffectSourceCodeKeys.ClassDeclaration).Split(' ', StringSplitOptions.RemoveEmptyEntries);
        var classDeclaration = string.Join(' ', modifiers.Contains("partial") ? modifiers : [.. modifiers, "partial"]);
        var fieldDeclaration = parameters.Get(EffectSourceCodeKeys.FieldDeclaration);
        var nameSpace = parameters.Get(EffectSourceCodeKeys.Namespace);
        var className = parameters.Get(EffectSourceCodeKeys.ClassName) ?? name;
        var fieldName = parameters.Get(EffectSourceCodeKeys.FieldName);

        string strideDefine = parameters.EffectParameters.Platform switch
        {
            GraphicsPlatform.Direct3D11 => "STRIDE_GRAPHICS_API_DIRECT3D11",
            GraphicsPlatform.Direct3D12 => "STRIDE_GRAPHICS_API_DIRECT3D12",
            GraphicsPlatform.Vulkan => "STRIDE_GRAPHICS_API_VULKAN",

            _ => "undefined"
        };

        string code = $$"""
            //------------------------------------------------------------------------------
            // <auto-generated>
            //     Stride Effect Compiler File Generated:
            //     Effect [{{name}}]
            //
            //     Generated by: {{generator}}
            //     Changes to this file may cause incorrect behavior and will be lost if
            //     the code is regenerated.
            // </auto-generated>
            //------------------------------------------------------------------------------

            #if {{strideDefine}}

            namespace {{nameSpace}}
            {
                {{classDeclaration}} class {{className}}
                {
                    {{fieldDeclaration}} static readonly byte[] {{fieldName}} = new byte[] {
            {{bufferAsText}}
                    };
                }
            }

            #endif

            """;
        // The line breaks of this file's checkout would otherwise end up in the output
        writer.Write(code.ReplaceLineEndings("\n"));
        writer.Flush();
    }
}
